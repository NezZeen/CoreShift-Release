/// What the engine says itself, worded by the app. The engine sends a code
/// and its arguments (engine/internal/msg): an event's `code` and `args`,
/// a checkup step's, a failed connection's `error_code` and `error_args`,
/// with the Russian text beside them for apps before the codes. The app
/// looks the code up here and fills the template in, as [tr] does; an
/// argument is a string, a number, another message `{code, args}` or a
/// list `{sep, items}`. A code the app does not know shows the engine's own
/// text.
///
/// [engineRu] is engine/internal/msg/catalog_ru.go to the letter (a test
/// compares them): add a code there first, then here, in both languages.
library;

import 'strings.dart';

/// [code] with [args] said in [to] (the current language by default); null
/// when it or a message among its arguments is not known.
String? engineMessage(String code, Object? args, [Lang? to]) {
  final l = to ?? lang;
  final a = args is Map ? args.cast<String, Object?>() : const <String, Object?>{};
  if (code == 'raw') return _rawText('${a['text'] ?? ''}', l);
  var t = l == Lang.en ? engineEn[code] : null;
  var tl = l;
  if (t == null) {
    t = engineRu[code];
    tl = Lang.ru;
  }
  if (t == null) return null;
  var known = true;
  String say(Object? v) {
    final s = _arg(v, l);
    if (s == null) known = false;
    return s ?? '';
  }

  // The words of the template's language, the arguments in [l].
  final out = fillTemplate(t, a, tl, say);
  return known ? out : null;
}

/// The engine's message in the current language, or [fallback], the text
/// the engine sent beside it, when [code] is empty or not known here.
String engineText(String code, Object? args, String fallback) {
  if (code.isEmpty) return fallback;
  return engineMessage(code, args) ?? fallback;
}

/// A message sent as JSON, `{code, args}`; null when it is not one or not
/// known.
String? engineJson(Object? m) => m is Map && m['code'] is String ? engineMessage(m['code'] as String, m['args']) : null;

String? _arg(Object? v, Lang l) {
  if (v == null) return '';
  if (v is String) return v;
  if (v is num) return '$v';
  if (v is Map && v['items'] is List) {
    final parts = <String>[];
    for (final m in v['items'] as List) {
      final s = _arg(m, l);
      if (s == null) return null;
      parts.add(s);
    }
    return parts.join('${v['sep'] ?? ', '}');
  }
  if (v is Map && v['code'] is String) return engineMessage(v['code'] as String, v['args'], l);
  return '$v';
}

/// A text that is not CoreShift's own is said as it is; only the
/// journal's stand-ins for what differs between repeated lines
/// (engine/internal/service/loggroup.go) are put in English.
String _rawText(String s, Lang l) {
  if (l == Lang.ru || !s.contains('<')) return s;
  return s.replaceAll('<имя>', '<name>').replaceAll('<адрес>', '<address>').replaceAll('<правило>', '<rule>');
}

